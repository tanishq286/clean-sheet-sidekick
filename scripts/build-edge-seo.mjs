#!/usr/bin/env node
/**
 * Compiles the app's JSON-LD builders into a Deno-compatible ESM module that
 * the Netlify Edge Function (netlify/edge-functions/profile-seo.ts) imports.
 *
 * Why this exists: the edge runtime is Deno, which cannot resolve TypeScript
 * path aliases ("@/types/founder") or extensionless imports. Rather than
 * hand-copying the schema logic — which would silently drift from the app —
 * we bundle src/lib/geo/schema.ts into a single dependency-free .mjs file.
 * One source of truth for structured data, on both the client and the edge.
 *
 * The output is committed so a deploy never depends on this step succeeding,
 * and regenerated on every build so it can never go stale.
 */

import { mkdir, writeFile, readFile } from "node:fs/promises";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { build } from "esbuild";

const ROOT = join(dirname(fileURLToPath(import.meta.url)), "..");
const OUTFILE = join(ROOT, "netlify", "lib", "seo.generated.mjs");

const BANNER = `// @generated by scripts/build-edge-seo.mjs — do not edit by hand.
// Source: src/lib/geo/schema.ts (+ its local imports).
// Regenerate with: npm run generate:edge-seo
`;

async function main() {
  await mkdir(dirname(OUTFILE), { recursive: true });

  const result = await build({
    entryPoints: [join(ROOT, "src/lib/geo/schema.ts")],
    bundle: true,
    write: false,
    format: "esm",
    // "neutral" keeps the output free of Node/browser assumptions so it runs
    // unchanged on Deno at the edge.
    platform: "neutral",
    target: "es2022",
    logLevel: "silent",
    alias: { "@": join(ROOT, "src") },
  });

  const next = BANNER + result.outputFiles[0].text;

  // Skip the write when nothing changed so the file's mtime (and git status)
  // stays quiet on repeat builds.
  const current = await readFile(OUTFILE, "utf8").catch(() => null);
  if (current === next) {
    console.log("[edge-seo] netlify/lib/seo.generated.mjs already up to date");
    return;
  }

  await writeFile(OUTFILE, next, "utf8");
  console.log("[edge-seo] wrote netlify/lib/seo.generated.mjs");
}

main().catch((err) => {
  // The committed copy is still valid, so a failure here must not break the
  // deploy — it only means the bundle wasn't refreshed this run.
  console.warn("[edge-seo] regeneration skipped:", err?.message ?? err);
  process.exitCode = 0;
});
